        <P>
          Four-colour process describes a smaller set of colours than the Pantone library does. That is
          not a defect in anyone’s software; it is arithmetic. A spot colour is one pre-mixed pigment
          laid down as a solid film at full strength, and the ink maker can reach for whatever pigment
          the colour needs. A process build has four transparent inks and a halftone screen, and every
          colour it can produce lies inside the volume those four inks can mix. Anything outside that
          volume gets pulled to the nearest point on its surface.
        </P>
