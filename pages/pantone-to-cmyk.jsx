/** The honest flag: how hard the build leans on a chromatic ink. */
function headroomFlag(row) {
  if (row.heavy > 0) {
    return (
      <span style={{ color: '#b91c1c', fontWeight: 700, fontSize: '0.74rem' }}>
        None — {row.maxInk}% ink
      </span>
    );
  }
  if (row.maxInk >= 80) {
    return <span style={{ color: '#9a3412', fontWeight: 700, fontSize: '0.74rem' }}>Tight — {row.maxInk}%</span>;
  }
  return <span style={{ color: '#6b7280', fontSize: '0.74rem' }}>Comfortable</span>;
}

