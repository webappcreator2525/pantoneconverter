/**
 * Builds the industrial colour-system palettes used by the /pantone-to-* and
 * /*-to-pantone converter pages into data/*.json.
 *
 *   node scripts/generate-palettes.mjs
 *
 * Each entry is written with rgb, cmyk and lab precomputed so the browser never
 * has to run a cube root per swatch per keystroke — the Pantone database alone
 * is 3,231 entries and these palettes are matched against it live.
 *
 * ── Data provenance ─────────────────────────────────────────────────────────
 * These are sRGB *approximations* of physical colour standards. None of the
 * bodies below publish free, machine-readable sRGB tables; the values here come
 * from the widely-circulated public conversions of each standard and are good
 * enough to rank a nearest match, but they are NOT a substitute for the official
 * fan decks. Confidence varies by system and is recorded in `accuracy` on each
 * palette so the pages can be honest about it:
 *
 *   ral       high     RAL Classic sRGB equivalents are consistently published.
 *   fs595     medium   Common FED-STD-595C chips; the full deck is ~650 chips.
 *   ncs       medium   Curated NCS Index standard colours.
 *   hks       medium   HKS K/N base numbers.
 *   toyo      low      Curated subset of the TOYO Color Finder 1050 series.
 *   trumatch  derived  Systematic reconstruction of the Trumatch CMYK ladder,
 *                      not a transcription of the licensed deck.
 *
 * Replacing any of these with licensed data is a drop-in: keep the shape
 * { code, name, localName?, hex } and re-run this script.
 */
