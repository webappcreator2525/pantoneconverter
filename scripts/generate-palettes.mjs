// ─── Trumatch ────────────────────────────────────────────────────────────────
// Trumatch is the one system here that is systematic rather than a lookup: the
// deck is a regular CMYK ladder, which is exactly what made it useful — every
// swatch on the fan deck maps to a printable CMYK build with no guesswork.
//
// This reconstructs that ladder rather than transcribing the licensed deck: 50
// hues evenly spaced around the wheel, each with four tint steps (a–d, chroma
// reduced in even increments at 0% black) and three shade steps (e–g, full
// chroma with black added in even increments), plus the four-colour grey scale.
// Codes therefore read like the real thing (18-c, 42-f) and land in the right
// region of colour space, but a production job should be specified from the
// physical Trumatch Colorfinder.
const TRUMATCH_HUES = 50;
const TRUMATCH_TINTS = [
  ['a', 1.00, 0],
  ['b', 0.82, 0],
  ['c', 0.64, 0],
  ['d', 0.46, 0],
  ['e', 1.00, 15],
  ['f', 1.00, 30],
  ['g', 1.00, 48],
];

function buildTrumatch() {
  const out = [];

  for (let hue = 1; hue <= TRUMATCH_HUES; hue += 1) {
    // Trumatch numbers hues starting at yellow and running through red, blue and
    // green, so offset the wheel to put hue 1 on yellow.
    const angle = (60 + (hue - 1) * (360 / TRUMATCH_HUES)) % 360;
    const base = hsvToRgb(angle, 100, 100);
    const baseCmyk = rgbToCmyk(base.r, base.g, base.b);

    for (const [letter, chroma, black] of TRUMATCH_TINTS) {
      const cmyk = {
        c: Math.round(baseCmyk.c * chroma),
        m: Math.round(baseCmyk.m * chroma),
        y: Math.round(baseCmyk.y * chroma),
        k: black,
      };
      const rgb = cmykToRgb(cmyk.c, cmyk.m, cmyk.y, cmyk.k);
      out.push({
        code: `TRUMATCH ${hue}-${letter}`,
        name: `TRUMATCH ${hue}-${letter}`,
        localName: `C${cmyk.c} M${cmyk.m} Y${cmyk.y} K${cmyk.k}`,
        hex: rgbToHex(rgb.r, rgb.g, rgb.b),
        rgb,
        cmyk,
        lab: rgbToLab(rgb.r, rgb.g, rgb.b),
      });
    }
  }

  // Four-colour grey scale, the deck's neutral run.
  for (let step = 1; step <= 12; step += 1) {
    const k = Math.round((step / 12) * 100);
    const rgb = cmykToRgb(0, 0, 0, k);
    out.push({
      code: `TRUMATCH ${step}-gray`,
      name: `TRUMATCH ${step}-gray`,
      localName: `C0 M0 Y0 K${k}`,
      hex: rgbToHex(rgb.r, rgb.g, rgb.b),
      rgb,
      cmyk: { c: 0, m: 0, y: 0, k },
      lab: rgbToLab(rgb.r, rgb.g, rgb.b),
    });
  }

  return out;
}

